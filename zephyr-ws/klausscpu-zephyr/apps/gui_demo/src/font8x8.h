static inline const uint8_t *font_glyph(char c)
{
	static const uint8_t blank[8] = { 0 };

	if (c >= 'a' && c <= 'z') {
		c -= 32;   /* fold lowercase to uppercase */
	}
	if (c < FONT_FIRST || c > FONT_LAST) {
		return blank;
	}
	return font8x8[c - FONT_FIRST];
}

