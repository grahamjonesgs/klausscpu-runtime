/* test_hwcg.c — the code the compiler emits for the klaussCPU 3508f87
 * instructions (ISA_ENCODING_V2_MAP.md section 8), on the emulator and the
 * board:
 *
 *   - fused compare-and-branch with the W predicates and with an imm32
 *     right-hand side: every predicate (signed and unsigned), taken and not
 *     taken, constants across the simm4 / simm8 / imm32 boundaries, operands
 *     whose upper 32 bits differ;
 *   - fused branches forward and backward at the largest distance the
 *     compiler still fuses and one block beyond (JMPcc);
 *   - 1-word CMPRVW.S, MULV.S / MULUV.S and LEAPC.S.
 *
 * test_hwcg_cases.h is generated by gen_test_hwcg.py, with every expected
 * value computed there.  Build at several -O levels (the cases only fuse
 * from -O1, and -O0 is the reference); the range cases are probed at -O2.
 *
 * Prints one line per failure and "=== ALL PASS ===" or a count.
 */
#include <stdint.h>
#include <stdio.h>

#include "test_hwcg_cases.h"

static int fails;
#define FAIL(...) do { if (fails < 40) { printf("FAIL " __VA_ARGS__); printf("\n"); } fails++; } while (0)

static unsigned hash_n;

static void test_branches(void) {
  unsigned bad = 0;
  for (unsigned f = 0; f < HW_N_BR1; f++) {
    for (unsigned i = 0; i < HW_NVALS; i++) {
      int want = (HW_BR1[f].m[i / 64] >> (i % 64)) & 1;
      int got = HW_BR1[f].f(HW_VALS[i]);
      hwcg_sink = 0;
      if (got != want) {
        FAIL("%s(0x%llx) = %d, want %d", HW_BR1[f].name, (unsigned long long)HW_VALS[i], got, want);
        bad++;
      }
    }
  }
  for (unsigned f = 0; f < HW_N_BR2; f++) {
    for (unsigned i = 0; i < HW_NPAIRV; i++)
      for (unsigned j = 0; j < HW_NPAIRV; j++) {
        unsigned k = i * HW_NPAIRV + j;
        int want = (HW_BR2[f].m[k / 64] >> (k % 64)) & 1;
        int got = HW_BR2[f].f(HW_PAIRV[i], HW_PAIRV[j]);
        if (got != want) {
          FAIL("%s(0x%llx, 0x%llx) = %d, want %d", HW_BR2[f].name, (unsigned long long)HW_PAIRV[i],
               (unsigned long long)HW_PAIRV[j], got, want);
          bad++;
        }
      }
  }
  printf("fused branches: %u + %u functions, %u wrong\n", (unsigned)HW_N_BR1, (unsigned)HW_N_BR2, bad);
}

static void test_ranges(void) {
  unsigned bad = 0;
  for (unsigned f = 0; f < HW_N_RNG; f++) {
    for (unsigned c = 0; c < HW_RNG[f].n; c++) {
      const struct hw_rcall *k = &HW_RNG[f].c[c];
      for (unsigned i = 0; i < 256; i++) g[i] = 0;
      int r = HW_RNG[f].f(k->a, k->b);
      unsigned ck = 0;
      for (unsigned i = 0; i < 200; i++) ck += (unsigned)g[i];
      if (r != k->ret || ck != k->ck) {
        FAIL("%s(0x%llx, 0x%llx) = %d checksum %u, want %d checksum %u", HW_RNG[f].name,
             (unsigned long long)k->a, (unsigned long long)k->b, r, ck, k->ret, k->ck);
        bad++;
      }
    }
  }
  printf("range cases: %u functions, %u wrong\n", (unsigned)HW_N_RNG, bad);
}

static void test_short(void) {
  unsigned bad = 0;
  for (unsigned f = 0; f < HW_N_CW; f++)
    for (unsigned i = 0; i < HW_NVALS; i++) {
      uint64_t b = 0x1122334455667788ull ^ HW_VALS[i];
      int want = (HW_CW[f].m[i / 64] >> (i % 64)) & 1;
      uint64_t got = HW_CW[f].f(HW_VALS[i], b);
      if (got != (want ? b : ~b)) {
        FAIL("%s(0x%llx)", HW_CW[f].name, (unsigned long long)HW_VALS[i]);
        bad++;
      }
    }
  printf("CMPRVW.S: %u functions, %u wrong\n", (unsigned)HW_N_CW, bad);
  bad = 0;
  for (unsigned f = 0; f < HW_N_MUL; f++)
    for (unsigned i = 0; i < HW_NVALS; i++) {
      uint64_t want = HW_VALS[i] * (uint64_t)HW_MUL[f].c;
      uint64_t got = HW_MUL[f].f(HW_VALS[i]);
      if (got != want) {
        FAIL("%s(0x%llx) = 0x%llx want 0x%llx", HW_MUL[f].name, (unsigned long long)HW_VALS[i],
             (unsigned long long)got, (unsigned long long)want);
        bad++;
      }
    }
  printf("MULV.S / MULUV.S: %u constants, %u wrong\n", (unsigned)HW_N_MUL, bad);
}

/* LEAPC.S: addresses within +-32 KiB of the instruction, in both directions.
 * Data after the code (the load reads what the linker placed at that
 * address) and functions before and after this one (called through the
 * address). */
static int lp_a = 0x1111, lp_b = 0x2222;
static volatile int lp_c[4] = {0x3333, 0x4444, 0x5555, 0x6666};
static const int lp_ro[4] = {0x7777, 0x8888, 0x9999, 0xaaaa};
__attribute__((noinline)) static int lp_f0(void) { return 100; }
__attribute__((noinline)) static int lp_f1(void) { return 101; }
__attribute__((noinline)) static int (*lp_pick(int i))(void) { return i ? lp_f1 : lp_f0; }
__attribute__((noinline)) static int *lp_addr_a(void) { return &lp_a; }
__attribute__((noinline)) static int *lp_addr_b(void) { return &lp_b; }
__attribute__((noinline)) static volatile int *lp_addr_c(int i) { return &lp_c[i]; }
__attribute__((noinline)) static const int *lp_addr_ro(int i) { return &lp_ro[i]; }
__attribute__((noinline)) static int lp_f2(void) { return 102; }
__attribute__((noinline)) static int (*lp_pick2(void))(void) { return lp_f2; }

static void test_leapc(void) {
  unsigned bad = 0;
  if (*lp_addr_a() != 0x1111) bad++;
  if (*lp_addr_b() != 0x2222) bad++;
  for (int i = 0; i < 4; i++) {
    if (*lp_addr_c(i) != 0x3333 + 0x1111 * i) bad++;
    if (*lp_addr_ro(i) != 0x7777 + 0x1111 * i) bad++;
  }
  if (lp_pick(0)() != 100 || lp_pick(1)() != 101 || lp_pick2()() != 102) bad++;
  /* The address is 32 bits: the upper half of the register is clear. */
  uint64_t p = (uint64_t)(uintptr_t)lp_addr_a();
  if (p >> 32) bad++;
  if (bad) FAIL("LEAPC.S: %u wrong", bad);
  printf("LEAPC.S: %u wrong\n", bad);
}

int main(void) {
  test_branches();
  test_ranges();
  test_short();
  test_leapc();
  if (fails) printf("FAILED: %d\n", fails);
  else printf("=== ALL PASS ===\n");
  return fails != 0;
}
