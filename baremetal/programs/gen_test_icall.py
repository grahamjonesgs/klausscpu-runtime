#!/usr/bin/env python3
"""Generate test_icall_cases.S / test_icall_cases.h for test_icall.c.

A regression test for the bug klaussCPU fixed in c1874cf (found on perf-hw
be78350, the 16 KiB I-cache): a posted store that the I-cache tag guard
refuses (its I-cache index matched a line fill installed since it issued)
squashed everything younger and refetched at the store's fall-through.  For
a CALL's return-address push the successor is the call target, so the
callee was skipped.  Linux hit it when a callee's line fill landed on the
same edge as the push to a stack slot with the same I-cache index.

So: NCALLEE one-line callees, 16 KiB apart, all at I-cache line index X
(direct mapped, 16 B lines: 16 KiB index bits [13:4], 8 KiB [12:4]), so
each call misses and fills; and a stack whose return-address slot lies in
line X + d (the driver picks d and the stack mode).  Each call site varies
the timing between the fill and the push:
  - 0..15 NOPs before the call;
  - the call form: callrel (short within +-512 KiB, long beyond: the two
    farthest callees) or callr through a register;
  - in ic_run_load, a D-cache-missing load first (a stall the fetch side
    can run ahead in);
  - the callee's entry at word 0..3 of its line (word 3: its ADDI spills
    into the next line);
and the stack mode: the same warm slot for every call, or (spstride 16384)
a cold slot per call, every one at the same I-cache index.

Each callee adds its own constant to r5, which the site zeroes before the
call and stores after it: a skipped callee leaves 0, a wrong one a wrong
constant.

Layout of the .text.icall section (aligned to 16 KiB): the two dispatchers
from offset 0 (kept below X's line in an 8 KiB cache too), then callee i at
16 KiB * (i + 1) + 16 * X + 4 * (i % 4).

  gen_test_icall.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NCALLEE = 36
X = 0x3F0                      # the callees' I-cache line index (16 KiB cache)
STRIDE = 16384
K = [0x100 + 17 * i for i in range(NCALLEE)]


def site_kind(i):
    """(form, nops) of call site i."""
    return ("callrel" if i % 2 == 0 else "callr"), (i // 2) % 16


def dispatcher(name, load):
    # ic_run_plain(out r0, sp r1, spstride r2)
    # ic_run_load(out r0, sp r1, spstride r2, cold r3)
    s = [f"\t.globl {name}", f"\t.type {name}, @function", f"{name}:"]
    s += ["\tpush\tr4", "\tpush\tr5", "\tpush\tr6", "\tpush\tr7",
          "\tsetru\tr6, ic_saved_sp", "\tgetsp\tr7", "\tstidx64\tr7, r6, 0",
          "\tsetr\tr4, 4128"]   # the cold-load stride: a new D-cache line and set
    for i in range(NCALLEE):
        form, nops = site_kind(i)
        s.append(f"\t// site {i}: {form}, {nops} nops{', after a load miss' if load else ''}")
        s.append("\tsetsp\tr1")
        if form == "callr":
            s.append(f"\tsetru\tr7, ic_f{i}")
        s.append("\tsetr\tr5, 0")
        if load:
            s.append("\tldidx64\tr6, r3, 0")
            s.append("\taddr\tr3, r3, r4")
        s += ["\tnop"] * nops
        s.append(f"\tcallrel\tic_f{i}" if form == "callrel" else "\tcallr\tr7")
        s.append(f"\tstidx64\tr5, r0, {8 * i}")
        s.append("\taddr\tr1, r1, r2")
    s += ["\tsetru\tr6, ic_saved_sp", "\tldidx64\tr6, r6, 0", "\tsetsp\tr6",
          "\tpop\tr7", "\tpop\tr6", "\tpop\tr5", "\tpop\tr4", "\tret",
          f"\t.size {name}, . - {name}"]
    return s


s = ["/* generated by gen_test_icall.py: do not edit */",
     "\t.section .text.icall,\"ax\",@progbits",
     f"\t.balign {STRIDE}",
     "ic_base:"]
s += dispatcher("ic_run_plain", False)
s += dispatcher("ic_run_load", True)
s.append("ic_disp_end:")
# The dispatchers must stay clear of the callees' lines (X - 4 .. X + 4) in
# an 8 KiB cache as well.  An .org can't move backwards, so this fails the
# assembly (after relaxation, unlike an .if) when they are too big.
s.append(f"\t.org ic_base + {16 * ((X % 512) - 4)}\t// dispatchers too big if this fails")
for i in range(NCALLEE):
    s.append(f"\t.org ic_base + {STRIDE * (i + 1) + 16 * X + 4 * (i % 4)}")
    s.append(f"\t.type ic_f{i}, @function")
    s.append(f"ic_f{i}:")
    s.append(f"\taddi\tr5, r5, {K[i]}")
    s.append("\tret")
s += ["\t.bss", "\t.balign 8", "ic_saved_sp:\t.skip 8"]
open(os.path.join(HERE, "test_icall_cases.S"), "w").write("\n".join(s) + "\n")

h = ["/* generated by gen_test_icall.py: do not edit */",
     f"#define IC_N {NCALLEE}",
     f"#define IC_X 0x{X:x}",
     f"#define IC_STRIDE {STRIDE}",
     "static const unsigned long ic_expect[IC_N] = {"]
h.append("  " + ", ".join(str(k) for k in K))
h.append("};")
h.append("static const char *const ic_form[IC_N] = {")
h.append("  " + ", ".join(f'"{site_kind(i)[0]}"' for i in range(NCALLEE)))
h.append("};")
h.append("static const unsigned char ic_nops[IC_N] = {")
h.append("  " + ", ".join(str(site_kind(i)[1]) for i in range(NCALLEE)))
h.append("};")
open(os.path.join(HERE, "test_icall_cases.h"), "w").write("\n".join(h) + "\n")
