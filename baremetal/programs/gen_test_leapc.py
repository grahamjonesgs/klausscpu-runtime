#!/usr/bin/env python3
"""Generate test_leapc_cases.S / test_leapc_cases.h for test_leapc.c.

LEAPC.S (klaussCPU 3508f87, ISA_ENCODING_V2_MAP.md section 8.3) is the 1-word
LEAPC for a target within +-32 KiB; the assembler picks it, so the boundary
is exercised by placing 40 labels (a magic word each) so that the distances
from 40 LEAPCs to their labels sweep +-156 bytes around 32768 (and -32768):

  data block A (40 words), 32 KiB of padding, code (40 LEAPCs, A[39-k] for
  the k-th), then 32 KiB of padding and data block B, read by 40 more LEAPCs
  placed before the padding.

Each probe loads the word its LEAPC points at and stores it in a result
array, so a wrong address (or a wrong PC base for a short one) reads the
wrong word.  The magic words are distinct.

  gen_test_leapc.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
N = 40
# padding that puts the sweep's middle on the boundary; the LEAPCs are 4 or 8
# bytes, so the exact distances depend on the assembler's choice
PAD_BEFORE = 32768 - 4 * N + 8
PAD_AFTER = 32768 - 4 * N - 8
magic = [0x1000 + 7 * i for i in range(2 * N)]

s = ["/* generated by gen_test_leapc.py: do not edit */", "\t.text", "\t.globl lp_run", "lp_run:"]
# forward probes first (code before data B), then backward (data A before code)
# Layout, in address order:
#   A (N words) | pad | code_back (N leapc, load, store) | code_fwd... 
# keep it simple: one code block, A before it, B after it.
s.append("\tjmprel\tlp_start")
s.append("\t.balign 4")
for i in range(N):
    s.append(f"LA{i}:\t.4byte 0x{magic[i]:x}")
s.append(f"\t.skip {PAD_BEFORE}")
s.append("lp_start:")
for k in range(N):
    j = N - 1 - k
    s.append(f"\tleapc\tr1, LA{j}")
    s.append("\tldidx32\tr2, r1, 0")
    s.append(f"\tstidx32\tr2, r0, {4 * k}")
for k in range(N):
    j = N - 1 - k
    s.append(f"\tleapc\tr1, LB{j}")
    s.append("\tldidx32\tr2, r1, 0")
    s.append(f"\tstidx32\tr2, r0, {4 * (N + k)}")
s.append("\tret")
s.append(f"\t.skip {PAD_AFTER}")
s.append("\t.balign 4")
for i in range(N):
    s.append(f"LB{i}:\t.4byte 0x{magic[N + i]:x}")
open(os.path.join(HERE, "test_leapc_cases.S"), "w").write("\n".join(s) + "\n")

h = ["/* generated by gen_test_leapc.py: do not edit */",
     f"#define LP_N {2 * N}",
     "static const unsigned lp_expect[LP_N] = {"]
exp = []
for k in range(N):
    exp.append(magic[N - 1 - k])
for k in range(N):
    exp.append(magic[N + N - 1 - k])
h.append("  " + ", ".join(f"0x{x:x}" for x in exp))
h.append("};")
open(os.path.join(HERE, "test_leapc_cases.h"), "w").write("\n".join(h) + "\n")
print("wrote test_leapc_cases.S/.h")
