#!/usr/bin/env bash
# run.sh — the Linux-port toolchain survey: compile/assemble/link each test
# with klausscpu-llvm and write RESULTS.md (PASS/FAIL and the exact errors).
# KLAUSSCPU_LLVM_BIN selects the toolchain (default ../../../klausscpu-llvm/build/bin).
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
B=${KLAUSSCPU_LLVM_BIN:-$HERE/../../../klausscpu-llvm/build/bin}
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
CC="$B/clang -target klausscpu-unknown-elf -O2 -ffreestanding -nostdlib -fno-PIE -fno-pic -c"
out=$HERE/RESULTS.md
{
echo "# Toolchain survey for the Linux port"
echo
echo "klausscpu-llvm: \`$(cd "$B/../.." 2>/dev/null && git log --oneline -1 2>/dev/null || echo "$B")\`"
echo "Generated by \`run.sh\` on $(date -u +%Y-%m-%d)."
echo
echo "| Test | What | Result |"
echo "|---|---|---|"
} >"$out"
fails=""
row() { # name what cmd...
  local n=$1 w=$2; shift 2
  if "$@" >"$T/log" 2>&1; then
    if grep -q "warning:" "$T/log"; then echo "| $n | $w | PASS (warning) |" >>"$out"; fails+=$'\n'"### $n (warning)"$'\n```\n'"$(grep -m5 -A2 warning: "$T/log")"$'\n```\n'
    else echo "| $n | $w | PASS |" >>"$out"; fi
  else
    echo "| $n | $w | **FAIL** |" >>"$out"
    fails+=$'\n'"### $n"$'\n```\n'"$(grep -v '^\s*$' "$T/log" | head -12)"$'\n```\n'
  fi
}
for f in "$HERE"/t*.c; do
  n=$(basename "$f" .c); w=$(sed -n '1s|^/\* *\(.*\) *\*/$|\1|p' "$f"); [ -n "$w" ] || w="$n"
  extra=""
  case $n in
    t14_*) extra="-ffixed-r13" ;;
    t15_*) extra="-fpatchable-function-entry=2" ;;
    t16_*) extra="-fstack-protector-strong" ;;
  esac
  row "$n" "$w" $CC $extra "$f" -o "$T/$n.o"
done
for f in "$HERE"/a*.S; do
  n=$(basename "$f" .S); w=$(sed -n '1s|^/\* *\(.*\) *\*/$|\1|p' "$f")
  row "$n" "$w" $CC "$f" -o "$T/$n.o"
done
# kernel-style link
row l01_link "kernel-style linker script (kseg VMA, AT() LMA, KEEP/PROVIDE/ASSERT/DISCARD)" \
  bash -c "$CC $HERE/l01_main.S -o $T/l1.o && $CC $HERE/l01_kmain.c -o $T/l2.o && $B/ld.lld -T $HERE/l01_kernel.lds $T/l1.o $T/l2.o -o $T/vmlinux && $B/llvm-readelf -lS $T/vmlinux | grep -q LOAD"
row l02_tools "objcopy -O binary, nm, readelf, objdump -dr, size, strip on the vmlinux" \
  bash -c "$B/llvm-objcopy -O binary $T/vmlinux $T/v.bin && $B/llvm-nm $T/vmlinux | grep -q kmain && $B/llvm-objdump -dr $T/vmlinux >/dev/null && $B/llvm-size $T/vmlinux >/dev/null && $B/llvm-strip -o $T/v.s $T/vmlinux"
row l03_ar "llvm-ar rcsT thin archive + link from it" \
  bash -c "$B/llvm-ar rcsT $T/lib.a $T/l2.o && $B/ld.lld -T $HERE/l01_kernel.lds $T/l1.o $T/lib.a -o $T/v2"
row l04_partial "ld.lld -r partial link (built-in.a / vmlinux.o style)" \
  bash -c "$B/ld.lld -r $T/l1.o $T/l2.o -o $T/part.o"
{
echo
echo "## Failures and warnings"
echo "${fails:-none}"
} >>"$out"
grep -c '\*\*FAIL' "$out" | sed 's/^/FAIL count: /'
